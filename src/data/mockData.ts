export function getTasksByApplication(appName: string): Task[] {
  return mockTasks.filter((t) => t.application === appName)
}

export function getOverdueTasks(tasks: Task[] = mockTasks): Task[] {
  const today = new Date().toISOString().split('T')[0]
  return tasks.filter((t) => t.dueDate < today && t.status !== 'done' && t.status !== 'cancelled')
}

export function getTaskStats(tasks: Task[] = mockTasks) {
  return {
    total: tasks.length,
    todo: tasks.filter((t) => t.status === 'todo').length,
    inProgress: tasks.filter((t) => t.status === 'in-progress').length,
    waiting: tasks.filter((t) => t.status === 'waiting').length,
    blocked: tasks.filter((t) => t.status === 'blocked').length,
    done: tasks.filter((t) => t.status === 'done').length,
    cancelled: tasks.filter((t) => t.status === 'cancelled').length,
    overdue: getOverdueTasks(tasks).length,
  }
}
